import assert from 'node:assert/strict';
import fs from 'node:fs';
const source=fs.readFileSync(new URL('../../src/components/syncProgressState.js',import.meta.url),'utf8');
const {activeStatus,progressJob,progressPercent}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
assert.equal(activeStatus('running'),true);
for(const status of ['completed','failed','interrupted','completed_with_issues'])assert.equal(progressJob([{id:'a',status}],null),null);
assert.equal(progressJob([{id:'a',status:'running'}],null,['a']),null);
assert.equal(progressJob([{id:'a',status:'running'}],{id:'a',status:'completed'}),null);
assert.equal(progressJob([{id:'a',status:'completed'}],{id:'a',status:'running'}),null);
assert.equal(progressJob([{id:'a',status:'running'},{id:'b',status:'running'}],null,['a']).id,'b');
assert.equal(progressPercent({total:0}),null);
assert.equal(progressPercent({total:10,counts:{details_processed:10,finished:0}}),50);
assert.equal(progressPercent({total:10,counts:{details_processed:10,finished:10}}),100);
assert.equal(progressPercent({total:1,counts:{details_processed:50,finished:50}}),100);
console.log('13 progress checks passed');
